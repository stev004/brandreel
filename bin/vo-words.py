#!/usr/bin/env python3
"""vo-words.py <workspace> <animatic-id> - Kokoro narration with word-level timing.

Reads <workspace>/vo.json ({voice, lang, speed, gapMs, chunkGapMs?, segments:[{id,text,gapMs?}]}),
synthesizes each segment, trims each chunk to its spoken words, and butts them together with
fixed short gaps so the narration runs continuously. Writes:
  <workspace>/vo.wav            24 kHz mono float narration
  <workspace>/vo-words.json     {durMs, segments:[{id,startMs,endMs}], words:[{w,s,e,seg}]}
  animatics/<id>.vo.js          var VO = <same json>  (loadable from file:// by the animatic)
Word times come from Kokoro's own token timestamps, so no separate aligner is needed.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

SR = 24_000


def main() -> None:
    ws, anim_id = Path(sys.argv[1]), sys.argv[2]
    cfg = json.loads((ws / "vo.json").read_text(encoding="utf-8"))
    from kokoro import KPipeline

    pipe = KPipeline(lang_code=cfg.get("lang", "b"), repo_id="hexgrad/Kokoro-82M")
    gap = int(SR * cfg.get("gapMs", 220) / 1000)
    chunk_gap = int(SR * cfg.get("chunkGapMs", 110) / 1000)
    lead_ms = cfg.get("leadMs", 400)
    out: list[np.ndarray] = [np.zeros(int(SR * lead_ms / 1000), dtype=np.float32)]
    cursor = len(out[0])
    words, segs = [], []
    for si, seg in enumerate(cfg["segments"]):
        if si:
            g = int(SR * seg["gapMs"] / 1000) if "gapMs" in seg else gap
            out.append(np.zeros(g, dtype=np.float32)); cursor += g
        seg_start = cursor
        for ci, res in enumerate(pipe(seg["text"], voice=cfg["voice"], speed=cfg.get("speed", 1.0))):
            audio = res.audio.numpy() if hasattr(res.audio, "numpy") else np.asarray(res.audio)
            toks = [t for t in res.tokens if t.start_ts is not None and t.end_ts is not None]
            if not toks:
                continue
            a = max(0, int((toks[0].start_ts - 0.04) * SR))
            b = min(len(audio), int((toks[-1].end_ts + 0.09) * SR))
            if ci:
                out.append(np.zeros(chunk_gap, dtype=np.float32)); cursor += chunk_gap
            clip = audio[a:b].astype(np.float32)
            fade = min(240, len(clip) // 4)
            clip[:fade] *= np.linspace(0, 1, fade); clip[-fade:] *= np.linspace(1, 0, fade)
            base_ms = (cursor - a) / SR * 1000
            for t in res.tokens:
                txt = t.text
                if t.start_ts is None or not txt.strip():
                    continue
                s, e = base_ms + t.start_ts * 1000, base_ms + t.end_ts * 1000
                if words and words[-1]["seg"] == seg["id"] and (not any(c.isalnum() for c in txt) or not words[-1]["ws"]):
                    words[-1]["w"] += txt; words[-1]["e"] = round(e); words[-1]["ws"] = bool(t.whitespace)
                    continue
                words.append({"w": txt, "s": round(s), "e": round(e), "seg": seg["id"], "ws": bool(t.whitespace)})
            out.append(clip); cursor += len(clip)
        segs.append({"id": seg["id"], "startMs": round(seg_start / SR * 1000), "endMs": round(cursor / SR * 1000)})
        print(f"{seg['id']:18s} {segs[-1]['startMs'] / 1000:7.2f}s -> {segs[-1]['endMs'] / 1000:7.2f}s", flush=True)
    wav = np.concatenate(out)
    sf.write(ws / "vo.wav", wav, SR, subtype="FLOAT")
    for w in words:
        w.pop("ws", None)
    data = {"durMs": round(len(wav) / SR * 1000), "segments": segs, "words": words}
    (ws / "vo-words.json").write_text(json.dumps(data, indent=1), encoding="utf-8")
    js = Path(__file__).resolve().parent.parent / "animatics" / f"{anim_id}.vo.js"
    js.write_text("// generated by bin/vo-words.py - do not edit\nvar VO = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"total {data['durMs'] / 1000:.1f}s, {len(words)} words -> {ws / 'vo.wav'}, {js}")


if __name__ == "__main__":
    main()
