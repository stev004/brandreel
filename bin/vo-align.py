#!/usr/bin/env python3
"""vo-align.py <workspace> <animatic-id> - word timings for a narration made by vo-chatterbox.py.

Runs in audio/.venv (stable-whisper). Each piece in <workspace>/vo-pieces.json is force-aligned
against its own display text (so captions and cues use the script's spelling, whatever the voice
was fed), then offset into the film. Each piece is also transcribed and compared with its text;
pieces below --min (default 0.86) are listed so they can be re-voiced with
`vo-chatterbox.py <workspace> --redo i,j`. Writes <workspace>/vo-words.json and
animatics/<id>.vo.js in the same shape as bin/vo-words.py.
"""
from __future__ import annotations

import difflib
import json
import re
import sys
from pathlib import Path

import numpy as np
import soundfile as sf


def main() -> None:
    ws, anim_id = Path(sys.argv[1]), sys.argv[2]
    lo = float(sys.argv[sys.argv.index("--min") + 1]) if "--min" in sys.argv else 0.86
    meta = json.loads((ws / "vo-pieces.json").read_text(encoding="utf-8"))
    wav, sr = sf.read(ws / "vo.wav", dtype="float32")
    import stable_whisper
    model = stable_whisper.load_model("small")
    words, bad, segs = [], [], {}
    norm = lambda s: re.sub(r"[^a-z0-9' ]", " ", s.lower().replace("-", " ")).split()
    for p in meta["pieces"]:
        a, b = int(p["startMs"] * sr / 1000), int(p["endMs"] * sr / 1000)
        clip = wav[a:b]
        clip16 = np.interp(np.arange(0, len(clip), sr / 16000), np.arange(len(clip)), clip).astype(np.float32)
        heard = model.transcribe(clip16, language="en", verbose=None).text
        ratio = difflib.SequenceMatcher(None, norm(p["text"]), norm(heard)).ratio()
        if ratio < lo:
            bad.append((p["i"], round(ratio, 2), p["text"][:50], heard.strip()[:80]))
        res = model.align(clip16, p["text"], language="en")
        for w in res.all_words():
            t = w.word.strip()
            if not t:
                continue
            words.append({"w": t, "s": round(p["startMs"] + w.start * 1000), "e": round(p["startMs"] + w.end * 1000), "seg": p["seg"]})
        sg = segs.setdefault(p["seg"], {"id": p["seg"], "startMs": p["startMs"], "endMs": p["endMs"]})
        sg["endMs"] = p["endMs"]
        print(f"{p['i']:3d} {ratio:.2f} {p['text'][:56]}", flush=True)
    data = {"durMs": meta["durMs"], "segments": list(segs.values()), "words": words}
    (ws / "vo-words.json").write_text(json.dumps(data, indent=1), encoding="utf-8")
    js = Path(__file__).resolve().parent.parent / "animatics" / f"{anim_id}.vo.js"
    js.write_text("// generated by bin/vo-align.py - do not edit\nvar VO = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"total {data['durMs'] / 1000:.1f}s, {len(words)} words -> {js}")
    if bad:
        print("RE-VOICE (low match):", ",".join(str(b[0]) for b in bad))
        for b in bad:
            print("  ", b)


if __name__ == "__main__":
    main()
